package com.ahrao.dto.academic.allocation;

import java.time.Instant;

public class AcademicAllocationDetailDto extends AcademicAllocationSummaryDto {

    private String allocatedToUserPhone;
    private String requestTitle;
    private String requestDescription;
    private String academicYearName;
    private String semesterName;
    private String timeSlotName;
    private String roomType;
    private String requesterRole;
    private String subjectName;
    private String sectionName;
    private Instant updatedAt;

    public AcademicAllocationDetailDto() {
    }

    public String getAllocatedToUserPhone() {
        return allocatedToUserPhone;
    }

    public void setAllocatedToUserPhone(String allocatedToUserPhone) {
        this.allocatedToUserPhone = allocatedToUserPhone;
    }

    public String getRequestTitle() {
        return requestTitle;
    }

    public void setRequestTitle(String requestTitle) {
        this.requestTitle = requestTitle;
    }

    public String getRequestDescription() {
        return requestDescription;
    }

    public void setRequestDescription(String requestDescription) {
        this.requestDescription = requestDescription;
    }

    public String getAcademicYearName() {
        return academicYearName;
    }

    public void setAcademicYearName(String academicYearName) {
        this.academicYearName = academicYearName;
    }

    public String getSemesterName() {
        return semesterName;
    }

    public void setSemesterName(String semesterName) {
        this.semesterName = semesterName;
    }

    public String getTimeSlotName() {
        return timeSlotName;
    }

    public void setTimeSlotName(String timeSlotName) {
        this.timeSlotName = timeSlotName;
    }

    public String getRoomType() {
        return roomType;
    }

    public void setRoomType(String roomType) {
        this.roomType = roomType;
    }

    public String getRequesterRole() {
        return requesterRole;
    }

    public void setRequesterRole(String requesterRole) {
        this.requesterRole = requesterRole;
    }

    public String getSubjectName() {
        return subjectName;
    }

    public void setSubjectName(String subjectName) {
        this.subjectName = subjectName;
    }

    public String getSectionName() {
        return sectionName;
    }

    public void setSectionName(String sectionName) {
        this.sectionName = sectionName;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }
}
